test('SECURITY: router (stale-knowledge alert): once KNOWLEDGE_STALE_ALERT_RATE_LIMIT_PER_HOUR is exhausted within the hour, further alerts are suppressed (no notifyAdmins call) but the entry is still stamped via markStaleKnowledgeAlertedFn so it does not retry-storm (issue #701 acceptance criterion 5c)', async () => {
  const makeInfo = (n: number): StaleInfo => ({
    title: `Entry ${n}`,
    content: 'content',
    updatedAt: new Date(),
  });
  const responses = new Map<number, StaleInfo[]>();
  const limit = 3; // config.knowledgeStaleAlert.rateLimitPerHour, per the env override above
  for (let i = 0; i < limit + 1; i += 1) {
    responses.set(i, [makeInfo(i)]);
  }
  const { router, notifyCalls, markStaleCalls } = makeRouterWithSpies(
    async (_caller, prompt: string) => ({
      text: 'reply',
      ok: true,
      turnState: { staleKnowledgeAlertIds: [Number(prompt.replace(/\D/g, ''))] },
    }),
    responses,
  );
  const { adapter, trigger } = makeAdapter();
  router.register(adapter);

  assert.equal(config.knowledgeStaleAlert.rateLimitPerHour, limit);
  for (let i = 0; i < limit; i += 1) {
    await trigger(makeMessage({ text: `capped entry ${i}`, conversationId: `chan-cap-${i}` }));
  }
  assert.equal(notifyCalls.length, limit, 'every serve within the cap must notify');

  // One more, past the cap.
  await trigger(makeMessage({ text: `capped entry ${limit}`, conversationId: 'chan-over-cap' }));

  assert.equal(notifyCalls.length, limit, 'the over-cap serve must not notify — the cap is not exceeded');
  assert.equal(
    markStaleCalls.length,
    limit + 1,
    'the over-cap serve must still be stamped via markStaleKnowledgeAlertedFn — unlike the knowledge-gap ' +
      'alert precedent, a rate-limited stale entry is never left unstamped, so it cannot retry-storm on ' +
      'every subsequent serve',
  );
});


test('router (knowledge_search stale alert): a served-stale id fires exactly one notifyAdmins call naming the title and a relative age, and stamps via markStaleKnowledgeAlertedFn (issue #701 acceptance criterion 1)', async () => {
  const info: StaleInfo = {
    title: 'Old parking rules',
    content: 'Park in the north lot only.',
    updatedAt: new Date(Date.now() - 20 * 86_400_000),
  };
  const { router, notifyCalls, markStaleCalls } = makeRouterWithSpies(
    async () => ({ text: 'Here is what I found.', ok: true, turnState: { staleKnowledgeAlertIds: [77] } }),
    new Map([[77, [info]]]),
  );
  const { adapter, sent, trigger } = makeAdapter();
  router.register(adapter);

  await trigger(makeMessage({ conversationId: 'chan-stale-1' }));

  assert.equal(sent[0].text, 'Here is what I found.', 'the member-facing reply is untouched');
  assert.deepEqual(markStaleCalls, [77], 'the served id must be passed to markStaleKnowledgeAlertedFn');
  assert.equal(notifyCalls.length, 1, 'exactly one notifyAdmins call');
  assert.match(notifyCalls[0].message, /Old parking rules/);
  assert.match(notifyCalls[0].message, /~20 days ago/);
  assert.equal(notifyCalls[0].excludeUserId, 'super-1');
});

test('router (knowledge_search stale alert): multiple stale ids served in one turn each fire their own notifyAdmins call (issue #701 acceptance criterion 1)', async () => {
  const infoA: StaleInfo = { title: 'Entry A', content: 'content a', updatedAt: new Date() };
  const infoB: StaleInfo = { title: 'Entry B', content: 'content b', updatedAt: new Date() };
  const { router, notifyCalls, markStaleCalls } = makeRouterWithSpies(
    async () => ({ text: 'reply', ok: true, turnState: { staleKnowledgeAlertIds: [1, 2] } }),
    new Map([
      [1, [infoA]],
      [2, [infoB]],
    ]),
  );
  const { adapter, trigger } = makeAdapter();
  router.register(adapter);

  await trigger(makeMessage({ conversationId: 'chan-stale-multi' }));

  assert.deepEqual(markStaleCalls.sort(), [1, 2]);
  assert.equal(notifyCalls.length, 2, 'each stale served entry gets its own notifyAdmins call');
});


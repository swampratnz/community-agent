function makeAdapter(overrides: Partial<PlatformAdapter> = {}): {
  adapter: PlatformAdapter;
  sent: OutgoingMessage[];
  trigger: (msg: IncomingMessage) => Promise<void>;
} {
  let handler: ((msg: IncomingMessage) => Promise<void> | void) | null = null;
  const sent: OutgoingMessage[] = [];
  const adapter: PlatformAdapter = {
    platform: 'discord',
    adminCapabilities: new Set(),
    async start() {},
    async stop() {},
    isConnected: () => true,
    onMessage(h) {
      handler = h;
    },
    async sendMessage(out) {
      sent.push(out);
    },
    async sendDirectMessage() {},
    async conversationsForUser() {
      return [];
    },
    async performAdminAction() {
      return '';
    },
    async sendTypingIndicator() {},
    ...overrides,
  };
  return {
    adapter,
    sent,
    trigger: async (msg) => {
      if (!handler) throw new Error('adapter.onMessage was never registered — call router.register() first');
      await handler(msg);
    },
  };
}

function makeMessage(overrides: Partial<IncomingMessage> = {}): IncomingMessage {
  return {
    platform: 'discord',
    conversationId: 'chan-1',
    userId: 'super-1',
    userName: 'Test User',
    text: 'what are the server rules?',
    isDirect: false,
    addressedToBot: true,
    timestamp: Date.now(),
    ...overrides,
  };
}

/** A fake `searchKnowledge` returning one fixed hit, regardless of query text. */
function fixedHitSearch(
  similarity: number,
  overrides: Partial<Awaited<ReturnType<SearchKnowledgeFn>>[number]> = {},
): SearchKnowledgeFn {
  return async () => [
    {
      id: 42,
      title: 'Rules',
      content: 'Be kind and follow the code of conduct.',
      similarity,
      updatedAt: new Date(),
      autoGenerated: false,
      sourceUrl: null,
      sourceTitle: null,
      verifiedAt: null,
      lastRetrievedAt: null,
      sourceUnreachable: null,
      sourceCheckedAt: null,
      ...overrides,
    },
  ];
}

/** Builds a full 8-arg Router so `checkLowRatedKnowledge` (the 8th ctor param) can be injected/spied. */
function makeRouter(opts: {
  runTurn?: ConstructorParameters<typeof Router>[0];
  searchKnowledgeForShortcut: SearchKnowledgeFn;
  recordShortcutRetrieval?: ConstructorParameters<typeof Router>[4];
  getLangPref?: ConstructorParameters<typeof Router>[6];
  checkLowRatedKnowledge: CheckLowRatedFn;
}): InstanceType<typeof Router> {
  return new Router(
    makeRouterDeps({
      runTurn:
        opts.runTurn ??
        (async () => {
          throw new Error('runTurn must not be called for a near-exact knowledge-shortcut match');
        }),
      typingRefireMs: 20,
      searchKnowledgeForShortcut: opts.searchKnowledgeForShortcut,
      recordShortcutRetrieval: opts.recordShortcutRetrieval ?? (async () => {}),
      getLangPref: opts.getLangPref,
      checkLowRatedKnowledge: opts.checkLowRatedKnowledge,
    }),
  );
}


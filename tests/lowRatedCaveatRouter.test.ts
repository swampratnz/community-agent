test('router (low-rated caveat): a low-rated entry served via the member shortcut gets the fixed caveat appended to the note (issue #337)', async () => {
  const calls: Array<[number, number]> = [];
  const router = makeRouter({
    searchKnowledgeForShortcut: fixedHitSearch(0.95),
    checkLowRatedKnowledge: async (entryId, minUnhelpful) => {
      calls.push([entryId, minUnhelpful]);
      return true;
    },
  });
  const { adapter, sent, trigger } = makeAdapter();
  router.register(adapter);

  await trigger(makeMessage());

  assert.equal(sent.length, 1);
  assert.match(sent[0].text, /Be kind and follow the code of conduct\./);
  assert.match(
    sent[0].text,
    new RegExp(KNOWLEDGE_LOW_RATED_CAVEAT_TEXT.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')),
  );
  assert.deepEqual(
    calls,
    [[42, 2]],
    'SECURITY: the served entry id and the configured threshold cross the render boundary — never a raw count',
  );
});

